import { expect, test, type APIRequestContext, type Page } from '@playwright/test';
import path from 'node:path';
import { readFile } from 'node:fs/promises';
import { catalogRecipes } from '../../catalog/catalog.js';
import type { PublishedWorkflow, WorkflowCase, WorkflowDraft, WorkflowPackage } from '../../shared/workflow-types.js';

test.use({ actionTimeout: 15_000 });

const recipe = catalogRecipes.find(item => item.kind === 'invoice')!;
const fixture = (id: string, name: string) => path.resolve('catalog/fixtures/invoice-development', id, name);
const sampleFiles = ['invoice.pdf', 'purchase-orders.xlsx', 'supplier-records.sqlite', 'policy.docx', 'letter-template.docx'].map(name => fixture('invoice-02', name));
async function drafts(request: APIRequestContext): Promise<WorkflowDraft[]> { return (await request.get('/api/workflow-drafts')).json(); }
async function cases(request: APIRequestContext): Promise<WorkflowCase[]> { return (await request.get('/api/cases')).json(); }
async function waitRevision(request: APIRequestContext, draftId: string, count: number) {
  await expect.poll(async () => (await drafts(request)).find(item => item.id === draftId)?.revisions.length, { timeout: 60_000 }).toBe(count);
}
async function uploadModal(page: Page, files: string[]) {
  if (await page.getByRole('dialog').getByRole('button', { name: 'Use different documents', exact: true }).count()) await page.getByRole('dialog').getByRole('button', { name: 'Use different documents', exact: true }).click();
  await page.getByRole('dialog').locator('input[type=file]').setInputFiles(files);
  await expect(page.getByRole('dialog').getByText('Uploading files…', { exact: true })).toHaveCount(0);
  await expect(page.getByRole('dialog').locator('.wf-file-chip')).toHaveCount(files.length);
}
async function selectedCase(page: Page, request: APIRequestContext): Promise<WorkflowCase> {
  const id = await page.evaluate(() => localStorage.getItem('office.workflow-case'));
  if (!id) throw new Error('No case is selected yet.');
  return (await request.get(`/api/cases/${id}`)).json();
}
async function waitCase(page: Page, request: APIRequestContext, status: WorkflowCase['status']) {
  await expect.poll(() => page.evaluate(() => localStorage.getItem('office.workflow-case'))).not.toBeNull();
  await expect(page.locator('.wf-case-title')).toBeVisible();
  await expect.poll(async () => (await selectedCase(page, request)).status, { timeout: 60_000 }).toBe(status);
  await expect(page.locator('.wf-case-title .wf-badge')).toHaveText(({blocked:'Needs correction',awaiting_review:'Ready for review',completed:'Done'} as Record<string,string>)[status] ?? status.replaceAll('_',' '));
}

