  await expect(review).toBeEnabled();
  await expect(review).not.toBeChecked();
  await expect(page.getByRole('button', { name: 'Publish workflow', exact: true })).toBeDisabled();
  await review.check();
  const publishing = page.waitForResponse(response => response.request().method() === 'POST' && response.url().endsWith(`/workflow-drafts/${imported.id}/publish`));
  await page.getByRole('button', { name: 'Publish workflow', exact: true }).click();
  const published: PublishedWorkflow = await (await publishing).json();
  expect(published.packageHash).toBe(imported.revisions[0].packageHash);
  expect(published.testReport.executionStatus).toBe('completed');
  expect(published.provenance[0].text).toContain('No AI authoring was performed.');

  // A plain package is accepted too, and creates another untested draft.
  const envelope = JSON.parse(await readFile(path.resolve('catalog/simple-invoice/reviewed-package.json'), 'utf8')) as { package: WorkflowPackage };
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('button', { name: 'Create workflow', exact: true }).click();
  const importingPlain = page.waitForResponse(response => response.request().method() === 'POST' && new URL(response.url()).pathname === '/api/workflow-drafts/import');
  await importInput.setInputFiles({ name: 'plain-package.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(envelope.package)) });
  const plain: WorkflowDraft = await (await importingPlain).json();
  expect(plain.id).not.toBe(imported.id);
  expect(plain.revisions[0].packageHash).toBe(imported.revisions[0].packageHash);
  expect(plain.revisions[0].testReports).toEqual([]);
  await expect(page.getByRole('button', { name: 'Publish workflow', exact: true })).toBeDisabled();
  expect(authorRequests).toBe(0);
  const afterRuns = await (await request.get('/api/e2e/observability')).json();
  expect(afterRuns.runs.length).toBe(beforeRuns.runs.length);
  await page.unrouteAll({ behavior: 'wait' });
  expect(browserErrors).toEqual([]);
