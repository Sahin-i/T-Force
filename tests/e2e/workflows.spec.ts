  const importing = page.waitForResponse(response => response.request().method() === 'POST' && new URL(response.url()).pathname === '/api/workflow-drafts/import');
  await importInput.setInputFiles(path.resolve('catalog/simple-invoice/reviewed-package.json'));
  const importResponse = await importing;
  expect(importResponse.status()).toBe(201);
  const imported: WorkflowDraft = await importResponse.json();
  expect(imported.importedFrom).toBe('reviewed-package.json');
  expect(imported.revisions).toHaveLength(1);
  expect(imported.revisions[0].runId).toBeUndefined();
  expect(imported.revisions[0].testReports).toEqual([]);
  expect(beforeDrafts.some(item => item.id === imported.id)).toBe(false);
  await expect.poll(() => page.evaluate(() => localStorage.getItem('office.workflow-draft'))).toBe(imported.id);
  await expect(page.getByText('Imported code still needs a sample test and your review before publication.', { exact: true })).toBeVisible();
  await expect(page.getByText(/No AI authoring was performed/)).toBeVisible();
  await expect(page.getByRole('button', { name: 'Generate workflow', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Refine workflow', exact: true })).toBeDisabled();
  const review = page.getByRole('checkbox', { name: 'I reviewed the workflow and its sample result.', exact: true });
  await expect(review).toBeDisabled();
  await expect(page.getByRole('button', { name: 'Publish workflow', exact: true })).toBeDisabled();
  await expect(page.getByRole('button', { name: 'Run sample test', exact: true })).toBeEnabled();
  await page.reload();
  await expect(page.getByText('Imported code still needs a sample test and your review before publication.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Run sample test', exact: true }).click();
  await uploadModal(page, ['invoice.pdf', 'purchase-order.pdf'].map(name => path.resolve('catalog/simple-invoice', name)));
  await page.getByRole('dialog').getByText('Advanced: structured inputs and test assertions', { exact: true }).click();
  await page.getByRole('textbox', { name: 'Test assertions JSON' }).fill(JSON.stringify([{ path: 'compare.disposition', operator: 'eq', value: 'ready' }, { path: 'compare.queueRecord.amount', operator: 'eq', value: '560.00' }]));
